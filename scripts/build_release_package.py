def rewrite_asset_paths(markdown: str) -> str:
    """Point a copied document at the package's own directories."""
    markdown = markdown.replace("docs/showcase/assets/readme/", "screenshots/")
    markdown = markdown.replace("docs/showcase/assets/article/", "screenshots/")
    markdown = markdown.replace("docs/showcase/assets/charts/", "charts/")
    markdown = markdown.replace("assets/readme/", "screenshots/")
    markdown = markdown.replace("assets/article/", "screenshots/")
    markdown = markdown.replace("assets/charts/", "charts/")
    markdown = markdown.replace(
        "docs/showcase/AWS_BUILDER_CENTER_ARTICLE.md", "AWS_BUILDER_CENTER_ARTICLE.md"
    )
    markdown = markdown.replace(
        "docs/showcase/ARTICLE_PUBLICATION_CHECKLIST.md", "ARTICLE_PUBLICATION_CHECKLIST.md"
    )
    markdown = markdown.replace(
        "docs/showcase/README_ASSET_MANIFEST.md", "README_ASSET_MANIFEST.md"
    )
    # Anything still pointing into the repository becomes a GitHub URL, because a
    # relative path out of this directory is a broken link once the folder moves.
    return re.sub(
        r"\]\((?!https?://|#|screenshots/|charts/|[A-Z_]+\.md)([^)]+)\)",
        lambda m: f"]({REPO}/blob/main/{m.group(1)})",
        markdown,
    )


def main() -> int:
    """Copy the assets, generate the derived documents, and checksum the lot."""
    metrics = json.loads((ASSETS / "source" / "chart-data" / "canonical-metrics.json").read_text())
    evidence = json.loads((ASSETS / "source" / "deployment-evidence.json").read_text())
    shots = json.loads((ASSETS / "source" / "screenshot-metadata.json").read_text())

    if metrics["run_kind"] != "aws_canonical" or metrics["simulated"]:
        raise SystemExit("chart data is not canonical; refusing to build a release package")
    if shots["fixture_mode"]:
        raise SystemExit("screenshot metadata reports fixture mode; refusing to build")

    OUT.mkdir(parents=True, exist_ok=True)
    for name in ("screenshots", "charts"):
        target = OUT / name
        if target.exists():
            shutil.rmtree(target)
        target.mkdir()

    for source in sorted((ASSETS / "readme").glob("*")):
        if source.suffix in {".png", ".gif"}:
            shutil.copy2(source, OUT / "screenshots" / source.name)
    for source in sorted((ASSETS / "article").glob("*.png")):
        shutil.copy2(source, OUT / "screenshots" / source.name)
    for source in sorted((ASSETS / "charts").glob("*.svg")):
        shutil.copy2(source, OUT / "charts" / source.name)

    shutil.copy2(ASSETS / "readme" / "08-architecture.svg", OUT / "architecture.svg")
    shutil.copy2(ASSETS / "readme" / "08-architecture.png", OUT / "architecture.png")
    shutil.copy2(ASSETS / "readme" / "cycle-sequence.svg", OUT / "cycle-sequence.svg")

    for name in (
        "AWS_BUILDER_CENTER_ARTICLE.md",
        "AWS_BUILDER_CENTER_ARTICLE_PASTE_READY.md",
        "ARTICLE_PUBLICATION_CHECKLIST.md",
        "README_ASSET_MANIFEST.md",
        "ARTICLE_ASSET_MANIFEST.md",
        "SCREENSHOT_CAPTURE_REPORT.md",
    ):
        (OUT / name).write_text(rewrite_asset_paths((SHOWCASE / name).read_text()))

    readme = (ROOT / "README.md").read_text()
    (OUT / "README.md").write_text(rewrite_asset_paths(readme))

    (OUT / "results-summary.md").write_text(results_summary(metrics))
    (OUT / "prediction-scorecard.md").write_text(prediction_scorecard())
    (OUT / "cost-and-sustainability.md").write_text(cost_and_sustainability())
    (OUT / "proof-of-aws-deployment.md").write_text(proof_of_deployment(evidence))

    export_manifest = {
        "run_id": "run_aws_canonical",
        "export_id": evidence["export"]["export_id"],
        "directory": evidence["export"]["directory"],
        "public_base_url": DATASET,
        "files": evidence["export"]["files"],
        "frozen_protocol_manifest": evidence["export"]["manifest_digest"],
        "verify": "curl the files listed in checksums.sha256, then sha256sum -c checksums.sha256",
        "note": (
            "The digests of the eighteen files live in the published checksums.sha256, "
            "not here: copying them into this repository would let the two disagree."
        ),
    }
    (OUT / "canonical-export-manifest.json").write_text(
        json.dumps(export_manifest, indent=2) + "\n"
    )

    article_words = words((SHOWCASE / "AWS_BUILDER_CENTER_ARTICLE.md").read_text())
    screenshots = sorted((OUT / "screenshots").glob("*"))
    charts = sorted((OUT / "charts").glob("*"))

    missing = [n for n in HAND_WRITTEN if not (OUT / n).exists()]

    manifest: dict[str, Any] = {
        "package": "showcase-2026",
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "readme_word_count": words(readme),
        "article_word_count": article_words,
        "screenshot_count": len(screenshots),
        "chart_count": len(charts),
        "app_url": APP,
        "api_url": API,
        "repository_url": REPO,
        "dataset_url": DATASET,
        "article_url": None,
        "publication_status": "DRAFT — not published; see ARTICLE_PUBLICATION_CHECKLIST.md",
        "canonical_run_id": metrics["run_id"],
        "run_kind": metrics["run_kind"],
        "run_status": metrics["status"],
        "cycles": f"{metrics['cycles']}/24",
        "protocol_version": metrics["protocol_version"],
        "memory_budget_tokens": metrics["memory_budget_tokens"],
        "token_count_source": metrics["token_count_source"],
        "source_commit": None,
        "frozen_protocol_manifest": evidence["export"]["manifest_digest"],
        "dataset_checksums": f"{DATASET}checksums.sha256",
        "qualification_gate": {
            "working_application_deployed_on_aws": True,
            "uses_aws_generative_ai_service": "Amazon Bedrock",
            "publicly_reachable": True,
            # Null, not True: this script reads local files and cannot see whether the
            # repository is readable when logged out. `validate_showcase_content.py`
            # checks it live, and reports a private repository as a blocking failure
            # because "source publicly available" is a qualification gate.
            "source_publicly_readable": None,
            "source_visibility_note": (
                "Checked live by scripts/validate_showcase_content.py, not asserted here."
            ),
            "article_drafted": True,
            "article_published": False,
        },
        "feature_worthy_gate": {
            "real_production_screenshots": True,
            "canonical_results_published": True,
            "preregistered_predictions_graded": True,
            "failed_predictions_reported": True,
            "dataset_downloadable_and_checksummed": True,
            "limitations_stated_before_claims": True,
            "no_fixture_data_presented_as_result": True,
        },
        "hand_written_documents_missing": missing,
        "asset_checksums": {f"screenshots/{p.name}": f"sha256:{digest(p)}" for p in screenshots}
        | {f"charts/{p.name}": f"sha256:{digest(p)}" for p in charts},
    }

    head = ROOT / ".git" / "HEAD"
    if head.exists():
        ref = head.read_text().strip()
        if ref.startswith("ref: "):
            ref_path = ROOT / ".git" / ref[5:]
            if ref_path.exists():
                manifest["source_commit"] = ref_path.read_text().strip()
        else:
            manifest["source_commit"] = ref
    (OUT / "release-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")

    lines = []
    for path in sorted(OUT.rglob("*")):
        if path.is_file() and path.name != "checksums.sha256":
            lines.append(f"{digest(path)}  {path.relative_to(OUT)}")
    (OUT / "checksums.sha256").write_text("\n".join(lines) + "\n")

    print(f"release package: {OUT.relative_to(ROOT)}")
    print(f"  {len(screenshots)} screenshots, {len(charts)} charts, {len(lines)} files checksummed")
    print(f"  README {manifest['readme_word_count']} words, article {article_words} words")
    if missing:
        print(f"  MISSING hand-written documents: {', '.join(sorted(missing))}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
