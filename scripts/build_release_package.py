def prediction_scorecard() -> str:
    """The eight preregistered predictions, graded, with the numbers behind each."""
    grid = table(
        ("#", "Prediction", "Verdict", "Evidence"),
        [(f"P{n}", claim, f"**{verdict}**", evidence) for n, claim, verdict, evidence in SCORECARD],
    )
    return f"""# Prediction scorecard — `run_aws_canonical`

The eight predictions in `experiment/pilot/predictions.md` were registered before the
first canonical cycle and are copied verbatim into every dataset export. They are graded
here against the stored run.

Generated by `scripts/build_release_package.py`. The verdicts are an editorial reading of
the stored numbers; each row carries the numbers it was read from, so the reading can be
disagreed with without being trusted.

**Two supported, two partially supported, two not supported, two inconclusive.**

{grid}

## The failure worth reading

P4 predicted that discounted citation weight would protect repeatedly-used seed memories
through the cycles 6 to 10 distractor flood better than plain recency would. It came
reversed. The citation-weighted arm ended the run pressed against its ceiling at 208 of
208 tokens, holding six seed memories — more than any other arm — and could state two of
six canonical facts. The recency arm held five seeds and could state three.

Holding the memory and being able to state the fact turned out not to be the same thing.

## The prediction that could not be graded

P6 required variance in whether an arm still held one particular fact. Every arm had
already lost it at cycle 0, in the sense that no arm's answer to that question was ever
scored as holding it. There was nothing to correlate. That is a defect in how the
prediction was specified, and it is recorded rather than quietly dropped.

Evidence: {API}/runs/run_aws_canonical/question-scores and
{API}/runs/run_aws_canonical/contradictions.
"""


