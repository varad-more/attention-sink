def words(markdown: str) -> int:
    """Word count of the prose, with images, links and code fences removed."""
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", markdown)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"```.*?```", "", text, flags=re.S)
    return len(text.split())


def table(header: tuple[str, ...], rows: list[tuple[str, ...]]) -> str:
    """A markdown table with padded columns, so the generated file is prettier-stable."""
    widths = [max(len(row[i]) for row in [header, *rows]) for i in range(len(header))]

    def line(cells: tuple[str, ...]) -> str:
        return "| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths, strict=True)) + " |"

    rule = "| " + " | ".join("-" * w for w in widths) + " |"
    return "\n".join([line(header), rule, *(line(row) for row in rows)])


def digest(path: Path) -> str:
    """The full SHA-256 of a file, as hex."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


